'use strict';

const assert = require('assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const puppeteer = require('puppeteer');
const { unusedPorts, startChild, stopChild, assertRunning, eventually, cleanEnvironment } = require('./smoke_packaged_app');

(async () => {
    const root = path.resolve(__dirname, '..');
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'fury-inspector-ui-'));
    const output = path.join(root, 'output', 'denick-inspector');
    fs.mkdirSync(output, { recursive: true });
    const [port] = await unusedPorts(1);
    const child = startChild(require('electron'), [path.join(root, 'scripts/denick-inspector/main.js'), '--fixture',
        `--remote-debugging-port=${port}`, '--remote-debugging-address=127.0.0.1'], cleanEnvironment(directory, root, 1, 1), 'Denick Inspector');
    let browser;
    try {
        browser = await eventually(async () => { assertRunning(child); return puppeteer.connect({ browserURL: `http://127.0.0.1:${port}`, defaultViewport: null }); }, 'Connecting inspector');
        const page = await eventually(async () => {
            const target = (await browser.pages()).find(item => item.url().endsWith('/denick-inspector/index.html'));
            assert(target); return target;
        }, 'Opening inspector');
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready.'));
        assert.equal(await page.$eval('#verifyBedsAhead', node => node.value), '0');
        assert.equal(await page.$eval('#singleStatFallbackRange', node => node.value), '200');
        assert.equal(await page.$eval('#bedsGapAllowancePercent', node => node.value), '25');
        assert.equal(await page.$eval('#lookupLimit', node => node.value), '50');
        assert.equal(await page.$eval('#verifyLimit', node => node.value), '25');
        assert((await page.$eval('#connection', node => node.textContent)).includes('OFFLINE FIXTURE'));
        assert((await page.$eval('#usage', node => node.textContent)).includes('Hypixel 0'));
        assert.deepEqual(await page.$$eval('link[rel=stylesheet]', nodes => nodes.filter(node => !node.sheet).map(node => node.href)), []);
        assert.equal(await page.$eval('h1', node => getComputedStyle(node).color), 'rgb(241, 243, 245)', 'Fury theme colors must load and keep the title readable');
        assert.equal(await page.evaluate(() => typeof window.require), 'undefined', 'renderer must not have Node access');
        const set = (id, value) => page.$eval(`#${id}`, (node, value) => { node.value = value; }, String(value));
        const click = id => page.locator(`#${id}`).click();
        const idle = () => page.waitForFunction(() => !document.body.hasAttribute('aria-busy'));
        await set('finals', 4529); await set('beds', 1874);
        await click('fetch'); await idle();
        assert.equal(await page.$$eval('#candidates tr', nodes => nodes.length), 3);
        assert((await page.$eval('#usage', node => node.textContent)).includes('Hypixel 0'));
        assert((await page.$eval('#candidates', node => node.textContent)).includes('profile not verified'));
        assert.equal(await page.$eval('#candidateMode', node => node.value), 'union');
        await set('candidateMode', 'intersection'); await click('analyze'); await idle();
        assert((await page.$eval('#candidates', node => node.textContent)).includes('missing from another stat list'));
        await set('candidateMode', 'union'); await click('analyze'); await idle();
        const auroraDifferences = () => page.$$eval('.aurora-comparison', nodes => nodes.map(node => node.firstChild.textContent));
        assert.deepEqual(await auroraDifferences(), ['-1 / —', '-29 / -14', '— / 0']);
        const beforeComparison = await page.$eval('#usage', node => node.textContent);
        await page.select('#aurora-reference', 'sharedplayer');
        assert.deepEqual(await auroraDifferences(), ['+28 / —', '0 / 0', '— / +14']);
        await page.select('#aurora-reference', 'hiddenplayer');
        assert.deepEqual(await auroraDifferences(), ['— / —', '— / -14', '— / 0'], 'missing reference counts remain unknown');
        await page.select('#aurora-reference', 'sharedplayer');
        assert.equal(await page.$eval('#usage', node => node.textContent), beforeComparison, 'comparing candidates sends no requests');
        await click('select-all'); await set('budget', 1); await click('verify'); await idle();
        assert((await page.$eval('#usage', node => node.textContent)).includes('Hypixel 1'));
        assert((await page.$eval('#checks', node => node.textContent)).includes('budget'));
        await set('budget', 5); await click('verify'); await idle();
        assert((await page.$eval('#usage', node => node.textContent)).includes('Hypixel 3'));
        assert((await page.$eval('#candidates', node => node.textContent)).includes('finals outside range'));
        const before = await page.$eval('#usage', node => node.textContent);
        await set('candidateMode', 'union'); await click('analyze'); await idle();
        assert.equal(await page.$eval('#aurora-reference', node => node.value), 'sharedplayer', 'comparison selection survives cached re-analysis');
        assert.equal(await page.$eval('#usage', node => node.textContent), before);
        assert((await page.$eval('#outcome', node => node.textContent)).includes('Current proxy would confirm'));
        assert.equal(await page.$eval('#mode', node => node.textContent), 'Current proxy rules');
        assert((await page.$eval('#candidates', node => node.textContent)).includes('4,467'));
        await page.setViewport({ width: 1280, height: 1000, deviceScaleFactor: 1 });
        await page.$eval('main', node => { node.scrollTop = 0; });
        await page.screenshot({ path: path.join(output, 'inspector.png'), fullPage: true });
        await page.$eval('main', node => { node.scrollTop = node.scrollHeight; });
        await page.screenshot({ path: path.join(output, 'inspector-results.png'), fullPage: true });
        await page.setViewport({ width: 900, height: 760, deviceScaleFactor: 1 });
        const overflow = await page.evaluate(() => document.querySelector('main').scrollWidth > document.querySelector('main').clientWidth);
        assert.equal(overflow, false, 'narrow window must not overflow outside the scrollable table');
        await set('candidateMode', 'intersection'); await set('verifyFinalsAhead', 100); await click('analyze'); await idle();
        assert((await page.$eval('#outcome', node => node.textContent)).includes('Experiment would confirm'));
        assert.equal(await page.$eval('#usage', node => node.textContent), before);
        await click('defaults'); await click('analyze'); await idle();
        assert.equal(await page.$eval('#mode', node => node.textContent), 'Current proxy rules');
        await set('finals', 4700); await set('beds', ''); await click('fetch'); await idle();
        assert((await page.$eval('#outcome', node => node.textContent)).includes('1 match(es) within 100 below; expanded to 200 below'));
        assert((await page.$eval('#candidates', node => node.textContent)).includes('Accepted by expanded single-stat range'));
        const beforeFallback = await page.$eval('#usage', node => node.textContent);
        await set('singleStatFallbackRange', 0); await click('analyze'); await idle();
        assert((await page.$eval('#outcome', node => node.textContent)).includes('Tentative stage: 1 match(es)'));
        await click('defaults'); await click('analyze'); await idle();
        assert((await page.$eval('#outcome', node => node.textContent)).includes('Tentative stage: 2 match(es)'));
        assert.equal(await page.$eval('#usage', node => node.textContent), beforeFallback, 'conditional widening reuses verified profiles');
        await set('player', 'HiddenPlayer'); await click('load-player'); await idle();
        assert.equal(await page.$eval('#finals', node => node.value), '4467');
        assert((await page.$eval('#usage', node => node.textContent)).includes('Hypixel 3'), 'name lookup reuses the profile cache');
        await set('finals', 4480); await set('beds', 1891); await click('fetch'); await idle();
        assert((await page.$eval('#candidates', node => node.textContent)).includes('beds gap 17 exceeds 16.25'));
        assert(!(await page.$eval('#outcome', node => node.textContent)).includes('would confirm'));
        const beforeGap = await page.$eval('#usage', node => node.textContent);
        await set('bedsGapAllowancePercent', 50); await click('analyze'); await idle();
        assert((await page.$eval('#outcome', node => node.textContent)).includes('Experiment would confirm'));
        await click('defaults'); await click('analyze'); await idle();
        assert(!(await page.$eval('#outcome', node => node.textContent)).includes('would confirm'));
        assert.equal(await page.$eval('#bedsGapAllowancePercent', node => node.value), '25');
        assert.equal(await page.$eval('#usage', node => node.textContent), beforeGap, 'gap allowance experiments send no extra API requests');
        await set('finals', '-1'); await click('fetch'); await idle();
        assert((await page.$eval('#status', node => node.textContent)).includes('Invalid finals'));
        assert((await page.$eval('#usage', node => node.textContent)).includes('Aurora 5'));
        assert.deepEqual(errors, []);
        console.log('Denick Inspector native Electron checks passed: discovery, explicit Hypixel verification, budgets, cache, experiments, current-proxy replay, validation and narrow layout. All HTTP was mocked.');
        console.log(`Screenshot: ${path.join(output, 'inspector.png')}`);
    } finally {
        if (browser) browser.disconnect();
        await stopChild(child);
        assert.equal(path.dirname(directory), path.resolve(os.tmpdir()));
        assert(path.basename(directory).startsWith('fury-inspector-ui-'));
        fs.rmSync(directory, { recursive: true, force: true, maxRetries: 3, retryDelay: 100 });
    }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
